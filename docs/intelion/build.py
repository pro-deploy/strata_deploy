def build():
    s = (HERE / "instruction.html").read_text()
    subs = {
        "DATE": "28.10.2026", "BOOT_MIN": "две-три минуты",
        "FIG14": term("fig14.txt"), "FIG15": term("fig15.txt"), "FIG16": term("fig16.txt"), "FIG17": term("fig17.txt"),
        "STAGES": STAGES, "PAR_ROWS": par_rows(), "PARALLEL_TEST": PARALLEL_TEST, "SECOND_MODEL": SECOND_MODEL,
        "EXTRA_ISSUES": EXTRA_ISSUES, "SUMMARY": SUMMARY,
    }
    for k, v in subs.items():
        assert "{{" + k + "}}" in s, k
        s = s.replace("{{" + k + "}}", v)
    left = re.findall(r"\{\{[A-Z0-9_]+\}\}", s)
    assert not left, left
    s = s.replace("–", "-")          # ranges with a plain hyphen
    for bad in ("—", "→", "←", "⇒", "⟶"):
        assert bad not in s, f"forbidden character {bad!r}"
    OUT.mkdir(exist_ok=True)
    shutil.copytree(HERE / "img", OUT / "img", dirs_exist_ok=True)
    (OUT / "instruction.html").write_text(s)
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--no-pdf-header-footer", "--allow-file-access-from-files",
                    f"--print-to-pdf={PDF}", (OUT / "instruction.html").as_uri()], check=True,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    print(PDF)


if __name__ == "__main__":
    sys.exit(build())
