def term(name):
    """A terminal protocol from logs/: escaped, with <in>...</in> typed input and <hl>...</hl> highlights."""
    text = html.escape((LOGS / name).read_text().rstrip("\n"))
    text = re.sub(r"&lt;in&gt;(.*?)&lt;/in&gt;", r'<span class="in">\1</span>', text)
    return re.sub(r"&lt;hl&gt;(.*?)&lt;/hl&gt;", r'<span class="hl">\1</span>', text)


def rows(cells_list):
    return "\n  ".join("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>" for cells in cells_list)


def par_rows():
    out = []
    for line in (LOGS / "parallel-qwen36.txt").read_text().splitlines()[1:]:
        n, wall, _toks, total, per, wait = line.split()
        f = lambda x: x.replace(".", ",")
        out.append([n, f(total), f(per), f(wait)])
    return rows(out)


